import datetime
import json
import sys
import re
from pathlib import Path

try:
    from okto import ollama_client
except ImportError:
    # If not running from the root as a package
    import ollama_client

OKTO_DIR = Path(".okto")

def _get_active_content(agent: str) -> str:
    """Reads the content of the agent's active task file."""
    file_path = OKTO_DIR / f"{agent}_active.md"
    if file_path.exists():
        return file_path.read_text(encoding="utf-8")
    return ""

def _update_scores(agent: str, task_desc: str, success: bool, retry_count: int):
    """Categorizes the task and updates the agent's category score in agents.md."""
    category_prompt = f"""Task: {task_desc}

Categorize this task into exactly one of these categories: code, analysis, file_ops, planning.
Return a JSON object in this format: {{"category": "category_name"}}
"""
    try:
        response = ollama_client.ask(category_prompt, think=False)
        category = response.get("category", "analysis").lower()
        if category not in ["code", "analysis", "file_ops", "planning"]:
            category = "analysis"
        
        # Calculate score
        if success:
            if retry_count == 0:
                calculated_score = 1.0
            elif retry_count == 1:
                calculated_score = 0.7
            else:
                calculated_score = 0.5
        else:
            calculated_score = 0.2
            
        agents_file = OKTO_DIR / "agents.md"
        if not agents_file.exists():
            return
            
        content = agents_file.read_text(encoding="utf-8")
        
        # Regex to find the agent section and specifically the score for the category
        # It looks for the agent header, then the scores block, then the specific category
        pattern = rf"(## {agent}.*?scores:.*?{category}:\s*)([0-9.]+)"
        
        def replacer(match):
            prefix = match.group(1)
            old_score = float(match.group(2))
            new_score = round((old_score * 0.8) + (calculated_score * 0.2), 2)
            return f"{prefix}{new_score}"

        new_content = re.sub(pattern, replacer, content, flags=re.DOTALL | re.IGNORECASE)
        
        if new_content != content:
            agents_file.write_text(new_content, encoding="utf-8")
            print(f"Updated {category} score for {agent} to {calculated_score} (weighted avg).")
            
    except Exception as e:
        print(f"Failed to update scores: {e}")

def _update_architecture(task_desc: str, agent_output: str):
    """Generates and appends a summary to architecture.md."""
    date_str = datetime.date.today().strftime("%Y-%m-%d")
    
    prompt = f"""Task Description: {task_desc}
Agent Results:
{agent_output}

Generate a very concise, one-sentence summary of what was achieved in this task for a project history log.
Return a JSON object in this format: {{"summary": "your concise summary here"}}
"""
    try:
        response = ollama_client.ask(prompt, think=False)
        summary = response.get("summary", "")
        if not summary:
            print("No summary generated by Ollama.")
            return

        print(f"\nSuggested summary for architecture.md:")
        print(f"## {date_str} - {task_desc}")
        print(summary)
        
        choice = input("Append this to architecture.md? (y/n): ").strip().lower()
        if choice == 'y':
            arch_file = OKTO_DIR / "architecture.md"
            # Ensure file exists or create it
            mode = "a" if arch_file.exists() else "w"
            with open(arch_file, mode, encoding="utf-8") as f:
                f.write(f"\n## {date_str} - {task_desc}\n{summary}\n")
            print("architecture.md updated.")
    except Exception as e:
        print(f"Failed to generate architecture summary: {e}")

def _update_agents(task_desc: str, agent: str, agent_output: str):
    """Generates and appends a note to the agent's section in agents.md."""
    prompt = f"""Agent: {agent}
Task: {task_desc}
Results: {agent_output}

Based on this task, suggest a very short note (max 10 words) about this agent's performance or project-specific experience to add to its log.
If nothing significant, return an empty string.
Return a JSON object in this format: {{"note": "your note here or empty string"}}
"""
    try:
        response = ollama_client.ask(prompt, think=False)
        note = response.get("note", "").strip()
        if not note:
            return

        print(f"\nSuggested note for {agent} in agents.md:")
        print(note)
        
        choice = input(f"Add this note to agents.md for {agent}? (y/n): ").strip().lower()
        if choice == 'y':
            agents_file = OKTO_DIR / "agents.md"
            if not agents_file.exists():
                print("agents.md not found. Skipping agent update.")
                return
            
            content = agents_file.read_text(encoding="utf-8")
            
            # Simple section-based replacement
            pattern = rf"(## {agent}.*?notes:)(.*?)(\n\n##|\Z)"
            
            def replacer(match):
                header_and_notes_label = match.group(1)
                existing_notes = match.group(2).strip()
                footer = match.group(3)
                
                new_notes = existing_notes
                if new_notes:
                    new_notes += f"\n- {note}"
                else:
                    new_notes = f"\n- {note}"
                
                return f"{header_and_notes_label} {new_notes}\n{footer}"

            new_content = re.sub(pattern, replacer, content, flags=re.DOTALL | re.IGNORECASE)
            
            if new_content != content:
                agents_file.write_text(new_content, encoding="utf-8")
                print(f"agents.md updated for {agent}.")
            else:
                print(f"Could not find section for {agent} in agents.md or format mismatch.")
                
    except Exception as e:
        print(f"Failed to generate agent note: {e}")

def update(task: dict, success: bool = True, retry_count: int = 0) -> None:
    """Entry point for updating project knowledge."""
    agent = task.get("agent", "unknown")
    task_desc = task.get("task", "Unknown Task")
    
    agent_output = _get_active_content(agent)
    
    _update_architecture(task_desc, agent_output)
    _update_agents(task_desc, agent, agent_output)
    _update_scores(agent, task_desc, success, retry_count)

